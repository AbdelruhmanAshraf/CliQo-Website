// Web derivatives only. Original supplied print files remain untouched.
import {readdir,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
const root=path.resolve('../products images');
const assets={stand:[],coaster:[],card:[]};
const manifest=[];
async function walk(dir){for(const entry of await readdir(dir,{withFileTypes:true})){const file=path.join(dir,entry.name);if(entry.isDirectory())await walk(file);else if(/\.png$/i.test(file))manifest.push(file);}}
await walk(root);manifest.sort();
for(const file of manifest){
 const rel=path.relative(root,file);const slug=rel.split(path.sep)[0].toLowerCase();
 if (/\bguide\b/i.test(rel)) continue;
 const key=rel.replace(/\.png$/i,'').toLowerCase().replace(/[^a-z0-9]+/g,'-');
 const label=/all.in.one/i.test(rel)?'All-in-One':/instapay/i.test(rel)?'InstaPay':/vodafone/i.test(rel)?'Vodafone Cash':/facebook/i.test(rel)?'Facebook':/instagram/i.test(rel)?'Instagram':/tiktok/i.test(rel)?'TikTok':/google/i.test(rel)?'Google Review':/white/i.test(rel)?'CliQo White':'CliQo Black';
 const side=/front/i.test(rel)?'front':/back/i.test(rel)?'back':null;
 const dest='public/products/artwork/'+key+'.webp';
 await mkdir(path.dirname(dest),{recursive:true});await sharp(file).resize({width:1400,height:1600,fit:'inside',withoutEnlargement:true}).webp({quality:90}).toFile(dest);
 await sharp(file).resize(900,900,{fit:'cover',position:'centre'}).webp({quality:88}).toFile(dest.replace('.webp','-detail.webp'));
 assets[slug].push({src:'/products/artwork/'+key+'.webp',label,side});
}
await writeFile('lib/product-artwork.ts','// Generated by scripts/import-product-artwork.mjs\nexport type ProductArtwork = {src:string;label:string;side:string|null;kind?:"mockup"};\nexport const productArtwork: Record<string, ProductArtwork[]> = '+JSON.stringify(assets,null,2)+';\n');
console.log('Imported '+Object.values(assets).reduce((total,items)=>total+items.length,0)+' supplied artwork images.');
